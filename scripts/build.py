#!/usr/bin/env python3
"""Bundle the JSON data files into assets/data.js.

The JSON files under data/ are the source of truth: scripts/verify.py reads
them directly, and they are what a reader should inspect. The browser gets a
generated JS bundle instead of fetching them, so that the site works when the
HTML is opened straight off disk (file://), where fetch() is blocked by CORS.

Run after any edit to data/:   python3 scripts/build.py
"""
import json, os, sys, datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
OUT = os.path.join(ROOT, "assets", "data.js")

FILES = {
    "countries": "countries.json",
    "organizations": "organizations.json",
    "species": "species.json",
    "sources": "sources.json",
    "report": "verification-report.json",
    "plates": "plates.json",
}


def main():
    bundle, missing = {}, []
    for key, name in FILES.items():
        path = os.path.join(DATA, name)
        if not os.path.exists(path):
            missing.append(name)
            bundle[key] = None
            continue
        with open(path, encoding="utf-8") as f:
            bundle[key] = json.load(f)

    bundle["builtAt"] = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    payload = json.dumps(bundle, ensure_ascii=False, separators=(",", ":"))
    # </script> inside a string literal would close the tag early
    payload = payload.replace("</", "<\\/")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("/* GENERATED by scripts/build.py — do not edit.\n")
        f.write("   Source of truth is the JSON under data/. */\n")
        f.write("window.FNDATA = " + payload + ";\n")

    kb = os.path.getsize(OUT) / 1024
    print("wrote assets/data.js  %.0f KB" % kb)
    for key in ("countries", "organizations", "species", "sources"):
        blob = bundle.get(key) or {}
        inner = [k for k in blob if not k.startswith("_")]
        for k in inner:
            if isinstance(blob[k], list):
                print("  %-14s %d" % (k, len(blob[k])))
    if missing:
        print("  (not yet generated: %s)" % ", ".join(missing))
    return 0


if __name__ == "__main__":
    sys.exit(main())
